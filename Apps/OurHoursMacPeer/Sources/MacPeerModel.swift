import AppKit
import Observation
import OurHoursCore
import UniformTypeIdentifiers

@MainActor
@Observable
final class MacPeerModel {
    struct Invite {
        let url: String
        let qrImage: CGImage
    }

    enum ExportFormat: Sendable {
        case json, sessionsCSV, eventsCSV

        var contentType: UTType {
            self == .json ? .json : .commaSeparatedText
        }

        var filename: String {
            switch self {
            case .json: "ourhours-diagnostics.json"
            case .sessionsCSV: "ourhours-sessions.csv"
            case .eventsCSV: "ourhours-events.csv"
            }
        }

        func data(from engine: OurHoursBLEEngine) -> Data {
            switch self {
            case .json: engine.exportJSONData()
            case .sessionsCSV: engine.exportSessionsCSVData()
            case .eventsCSV: engine.exportEventsCSVData()
            }
        }
    }

    private enum ExportError: LocalizedError {
        case unavailable

        var errorDescription: String? {
            "The engine could not read the saved diagnostic data."
        }
    }

    private let engine = OurHoursBLEEngine(enableStateRestoration: false)
    @ObservationIgnored private var snapshotTask: Task<Void, Never>?

    private(set) var snapshot: EngineSnapshot
    private(set) var mergedIntervals: [MergedReferenceInterval]
    private(set) var invite: Invite?
    private(set) var didCopyInvite = false
    private(set) var pairingError: String?
    private(set) var isExporting = false

    init() {
        engine.start()
        let initialSnapshot = engine.currentSnapshot()
        snapshot = initialSnapshot
        mergedIntervals = EncounterSession.mergedReferenceIntervals(from: initialSnapshot.sessions)

        let stream = engine.snapshotStream()
        snapshotTask = Task { [weak self] in
            for await update in stream {
                guard let self, !Task.isCancelled else { break }
                if snapshot.sessions != update.sessions {
                    mergedIntervals = EncounterSession.mergedReferenceIntervals(from: update.sessions)
                }
                snapshot = update
            }
        }
    }

    deinit {
        snapshotTask?.cancel()
    }

    func generateInviteBundle() {
        pairingError = nil
        let existingPair = engine.currentSnapshot().pairConfiguration
        let config: PairConfiguration
        let url: String
        if let existingPair {
            config = existingPair
            url = PairingPayloadCodec.encode(existingPair, for: existingPair.localRole.opposite)
        } else {
            let bundle = PairingPayloadCodec.makePairingBundle()
            config = bundle.localConfiguration
            url = bundle.peerQRPayload
        }

        guard let qrImage = PairingPayloadCodec.generateQRCodeCGImage(from: url) else {
            pairingError = "Could not generate the invite QR code."
            return
        }
        if existingPair == nil, !configurePair(config) {
            return
        }
        didCopyInvite = false
        invite = Invite(url: url, qrImage: qrImage)
    }

    func hideInvite() {
        invite = nil
        didCopyInvite = false
    }

    func copyInviteURL() {
        guard let invite else { return }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        didCopyInvite = pasteboard.setString(invite.url, forType: .string)
        pairingError = didCopyInvite ? nil : "Could not copy the invite URL to the clipboard."
    }

    @discardableResult
    func applyPastedPairingURL(_ url: String) -> Bool {
        pairingError = nil
        do {
            let config = try PairingPayloadCodec.decode(url)
            if let current = snapshot.pairConfiguration,
               config.pairID == current.pairID,
               config.keyEpoch == current.keyEpoch,
               config.localRole != current.localRole {
                pairingError = "This invite URL was generated by this Mac for the peer device."
                return false
            }
            guard configurePair(config) else { return false }
            hideInvite()
            return true
        } catch {
            switch error as? PairingPayloadError {
            case .invalidParameters:
                pairingError = "The pairing URL is incomplete. Copy the full invite URL."
            case .invalidPairID:
                pairingError = "The pairing URL contains an invalid pair ID."
            case .invalidSecret:
                pairingError = "The pairing URL contains an invalid key."
            case .invalidRole:
                pairingError = "The pairing URL must assign role A or B."
            case .invalidEpoch:
                pairingError = "The pairing URL contains an invalid key epoch."
            case .invalidShareURL:
                pairingError = "The pairing URL contains an invalid iCloud share link."
            case .invalidURL, nil:
                pairingError = "Enter a valid OurHours invite URL beginning with ourhours://pair/v1?."
            }
            return false
        }
    }

    func unpair() {
        engine.unpair()
        hideInvite()
        pairingError = nil
    }

    func setAutoRecordingEnabled(_ enabled: Bool) {
        engine.setAutoRecordingEnabled(enabled)
    }

    func setAdvertisingOverride(_ enabled: Bool) {
        engine.setAdvertisingOverride(enabled)
    }

    func setScanningOverride(_ enabled: Bool) {
        engine.setScanningOverride(enabled)
    }

    func simulateDisconnect() {
        engine.simulateDisconnect()
    }

    func simulateEngineRestart() {
        engine.simulateEngineRestart()
    }

    func clearLogs() {
        engine.clearLogs()
    }

    func handleForegroundActivation() {
        engine.handleForegroundActivation()
    }

    func export(_ format: ExportFormat) async throws {
        guard !isExporting else { return }
        isExporting = true
        defer { isExporting = false }

        let panel = NSSavePanel()
        panel.title = "Export Diagnostics"
        panel.allowedContentTypes = [format.contentType]
        panel.nameFieldStringValue = format.filename
        panel.canCreateDirectories = true
        guard await panel.begin() == .OK, let url = panel.url else { return }

        try await Task.detached(priority: .userInitiated) { [engine] in
            let data = format.data(from: engine)
            guard !data.isEmpty else { throw ExportError.unavailable }
            try data.write(to: url, options: .atomic)
        }.value
    }

    private func configurePair(_ config: PairConfiguration) -> Bool {
        engine.configurePair(config)
        let result = engine.currentSnapshot()
        guard result.pairConfiguration == config else {
            pairingError = result.lastErrorMessage ?? "Could not save the pair configuration."
            return false
        }
        return true
    }
}
